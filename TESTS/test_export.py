from __future__ import annotations

import json
import shutil

import yaml
from conftest import FIXTURES, REPO_ROOT

from harness import export
from harness.cli import main
from harness.model import load_repository, split_frontmatter
from harness.resolve import compose


def run_compose(project, profile="ITAU", task="feature"):
    repo = load_repository(REPO_ROOT)
    comp = compose(repo, profile, task, project)
    files = export.render(repo, comp, project)
    export.write(project, files)
    return files


def project_copy(tmp_path):
    target = tmp_path / "java-service"
    shutil.copytree(FIXTURES / "java-service", target)
    return target


def test_exported_skills_follow_agent_skills_spec(tmp_path):
    project = project_copy(tmp_path)
    run_compose(project)
    for base in (".agents/skills", ".claude/skills"):
        skill_files = list((project / base).glob("*/SKILL.md"))
        assert skill_files
        for f in skill_files:
            fm, body = split_frontmatter(f.read_text(encoding="utf-8"))
            assert fm["name"] == f.parent.name
            assert 0 < len(fm["description"]) <= 1024
            assert set(fm) <= {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}
            assert all(isinstance(v, str) for v in fm["metadata"].values())
            assert "GENERATED by engineering-harness" in body


def test_personas_get_profile_models(tmp_path):
    project = project_copy(tmp_path)
    run_compose(project)
    analyst, _ = split_frontmatter((project / ".claude/agents/analyst.md").read_text(encoding="utf-8"))
    assert analyst["model"] == "claude-opus-5-5"
    developer, body = split_frontmatter((project / ".claude/agents/developer.md").read_text(encoding="utf-8"))
    assert developer["model"] == "inherit"  # ITAU developer runs on Devin, not Claude
    assert "devin" in body and "NOT confirmed" in body
    reviewer, _ = split_frontmatter((project / ".opencode/agents/reviewer.md").read_text(encoding="utf-8"))
    assert reviewer["permission"] == {"edit": "deny"} and reviewer["mode"] == "subagent"
    script = (project / ".harness/maestri-roles.ps1").read_text(encoding="utf-8")
    assert "maestri role" in script and "git rev-parse --show-toplevel" in script
    assert '--command "claude --model claude-opus-5-5"' in script  # analyst pinned to its model
    assert "Developer: tool 'devin' has no Maestri preset" in script


def test_maestri_recruits_pin_profile_models(tmp_path):
    project = project_copy(tmp_path)
    run_compose(project, profile="PERSONAL")
    script = (project / ".harness/maestri-roles.ps1").read_text(encoding="utf-8")
    assert '--role "Developer" --command "opencode -m opencode-go/deepseek-v4.1-flash"' in script
