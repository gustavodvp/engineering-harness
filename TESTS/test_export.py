def test_drift_detects_hand_edits_and_stale_files_are_removed(tmp_path):
    project = project_copy(tmp_path)
    run_compose(project)
    assert export.drift(project) == []
    skill = project / ".claude/skills/java-spring-boot/SKILL.md"
    skill.write_text(skill.read_text(encoding="utf-8") + "\nhand edit\n", encoding="utf-8")
    agents = project / "AGENTS.md"
    agents.write_text("Project text outside the block is free to change.\n" + agents.read_text(encoding="utf-8"),
                      encoding="utf-8")
    problems = export.drift(project)
    assert len(problems) == 1 and "java-spring-boot" in problems[0]
    run_compose(project, task="support")
    assert not (project / ".claude/skills/story-delivery").exists()
    assert export.drift(project) == []


def test_cli_compose_refuses_to_write_on_conflict(mini, tmp_path, capsys):
    mini.unit("rule", "merge", decides="git.merge-strategy=merge-commit")
    mini.unit("rule", "squash", profile="ACME", decides="git.merge-strategy=squash")
    project = tmp_path / "proj"
    project.mkdir()
    code = main(["--root", str(mini.root), "compose", str(project), "--profile", "ACME", "--task", "feature"])
    assert code == 3
    assert not (project / ".harness").exists()
    assert "git.merge-strategy" in capsys.readouterr().out


