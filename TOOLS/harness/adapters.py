"""Render canonical units into the files each agent tool reads.

Every generated file carries a GENERATED marker pointing at its canonical source.
Formats (verified 2026-10):
- Agent Skills: `<dir>/<name>/SKILL.md` (agentskills.io/specification) - Claude Code reads .claude/skills,
  OpenCode reads .claude/skills, .agents/skills and .opencode/skills, Devin CLI and Codex read .agents/skills.
- Claude Code subagents: `.claude/agents/<name>.md` (name, description, model, disallowedTools).
- OpenCode agents: `.opencode/agents/<name>.md` (description, mode, model, permission).
- AGENTS.md: always-on rules (Devin CLI, OpenCode, Codex; Claude Code via CLAUDE.md `@AGENTS.md`).
- Maestri: roles created with `maestri role create/write` from a script, prompt points at a persona file.
"""

from __future__ import annotations

import yaml

from .model import Profile, Unit

AGENTS_BEGIN = "<!-- harness:begin (generated by `harness compose`; edit the canonical sources, not this block) -->"
AGENTS_END = "<!-- harness:end -->"


def generated_note(unit: Unit, root) -> str:
    rel = unit.path.relative_to(root).as_posix()
    return f"<!-- GENERATED by engineering-harness from {rel} ({unit.id} v{unit.m('version')}). Do not edit. -->"


def _dump(data: dict) -> str:
    return yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000).strip()


def agent_skill(unit: Unit, root) -> str:
    """Skills and workflows keep their spec-compliant frontmatter unchanged."""
    return f"---\n{_dump(unit.frontmatter)}\n---\n{generated_note(unit, root)}\n{unit.body.lstrip()}"


def _assignment(profile: Profile, persona: str) -> dict:
    return profile.models.get(persona) or {}


def _read_only(unit: Unit) -> bool:
    return unit.m("edits-code", "true") == "false"


def _executor_note(profile: Profile, persona: str) -> str:
    a = _assignment(profile, persona)
    if not a:
        return f"Profile {profile.name} assigns no preferred model to this persona."
    status = "confirmed" if a.get("confirmed") else "NOT confirmed yet - verify availability before relying on it"
    return f"Profile {profile.name}: preferred executor `{a['tool']}` with model `{a['model']}` ({status})."


def persona_body(unit: Unit, profile: Profile, root) -> str:
    return (f"{generated_note(unit, root)}\n\n> {_executor_note(profile, unit.name)}\n"
            f"> Rules in force are in AGENTS.md; the resolution report is .harness/resolution.md.\n\n"
            f"{unit.body.strip()}\n")


def claude_agent(unit: Unit, profile: Profile, root) -> str:
    a = _assignment(profile, unit.name)
    fm = {"name": unit.name, "description": unit.description}
    fm["model"] = a["model"] if a.get("tool") == "claude-code" else "inherit"
    if _read_only(unit):
        # Read-only personas still write their evidence files; they must not edit existing code.
        fm["disallowedTools"] = "Edit, NotebookEdit"
    return f"---\n{_dump(fm)}\n---\n{persona_body(unit, profile, root)}"


def opencode_agent(unit: Unit, profile: Profile, root) -> str:
    a = _assignment(profile, unit.name)
    fm: dict = {"description": unit.description, "mode": "primary" if unit.name == "orchestrator" else "subagent"}
    if a.get("tool") == "opencode":
        fm["model"] = a["model"]
    if _read_only(unit):
        fm["permission"] = {"edit": "deny"}
    return f"---\n{_dump(fm)}\n---\n{persona_body(unit, profile, root)}"


MAESTRI_COMMANDS = {
    "claude-code": "claude --model {model}",
    "opencode": "opencode -m {model}",
    "codex": "codex --no-daemon -m {model}",
}


def maestri_role_name(unit: Unit) -> str:
    """'qa' -> 'QA', 'developer' -> 'Developer'."""
    return " ".join(w.upper() if len(w) <= 2 else w.capitalize() for w in unit.name.split("-"))


def maestri_recruit_command(unit: Unit, profile: Profile) -> str | None:
    """The CLI command a recruit runs; it pins the model the profile assigns to the persona."""
    a = _assignment(profile, unit.name)
    template = MAESTRI_COMMANDS.get(a.get("tool", ""))
    return template.format(model=a["model"]) if template else None


def maestri_script(personas: list[Unit], profile: Profile, project_rel: str) -> str:
    """PowerShell script to run inside a Maestri terminal. Roles point at generated persona files.

    Recruits start in `.maestri/roles/<id>`, so prompts locate the project from the git root:
    `project_rel` is the project path relative to `git rev-parse --show-toplevel` ('.' for the root).
    That stays valid on every Maestri floor, because floors are worktrees or clones with the same layout.
    """
    where = "the git repository root" if project_rel == "." else f"`{project_rel}` under the git repository root"
    lines = [
        "# GENERATED by engineering-harness (`harness compose`). Run inside a Maestri terminal:",
        "#   pwsh -File .harness/maestri-roles.ps1 [-Scope current|global]",
        "# Creates or updates one Maestri role per persona (default: scoped to the current workspace).",
        "param([ValidateSet('current', 'global')][string]$Scope = 'current')",
        "$ErrorActionPreference = 'Stop'",
        "$maestri = if (Get-Command maestri -ErrorAction SilentlyContinue) { 'maestri' } else { $env:MAESTRI_CLI }",
        "if (-not $maestri) { throw 'maestri CLI not found: run this inside a Maestri terminal' }",
        # Role commands are Maestro-only; a recruit running this got 'This terminal is not the Maestro' (DEMO-1).
        "$probe = & $maestri role list 2>&1",
        "if (\"$probe\" -match 'not the Maestro') { throw 'Run this script in the Maestro terminal (Maestro Mode on): "
        "role commands are not available to recruits.' }",
    ]
    for unit in personas:
        role = maestri_role_name(unit)
        prompt = (f"You are the {role} persona of the engineering harness ({profile.name} profile). Your project "
                  f"is the folder the orchestrator names in your task, by default {where} (run git rev-parse --show-toplevel); cd there before anything else, because you "
                  f"start inside .maestri/roles and must never commit the .maestri folder. Then read "
                  f".harness/personas/{unit.name}.md and AGENTS.md in the project and follow them. Run maestri list "
                  f"to see your teammates. Write stage evidence to .harness/runs/<story>/ as the story-delivery "
                  f"workflow requires, keep maestri floor status current, and when a task is done report back with "
                  f"maestri ask to whoever assigned it.")
        prompt = prompt.replace("'", "''")
        lines += [
            # Exact name: try to update, create when the CLI says the role doesn't exist. A regex over
            # `role list` matched similar names (QA vs "QA Frontend Atlas") in the DEMO-1 run.
            f"$out = & $maestri role write '{role}' '{prompt}' 2>&1",
            f"if ($LASTEXITCODE -ne 0 -or \"$out\" -match 'No role named') {{",
            f"  & $maestri role create '{role}' '{prompt}' --scope $Scope",
            f"  if ($LASTEXITCODE -ne 0) {{ throw \"maestri role create '{role}' failed\" }}",
            f"  Write-Output 'created role {role}'",
            f"}} else {{ Write-Output 'updated role {role}' }}",
        ]
    lines += ["", "# Recruits: the command pins the model the profile assigns to each persona."]
    for unit in personas:
        a = _assignment(profile, unit.name)
        command = maestri_recruit_command(unit, profile)
        status = "confirmed" if a.get("confirmed") else "unconfirmed"
        if command:
            lines.append(f"#   maestri recruit \"<codename>\" --role \"{maestri_role_name(unit)}\" "
                         f"--command \"{command}\" [--floor \"<story>\"]   # {status}")
        else:
            lines.append(f"#   {maestri_role_name(unit)}: tool '{a.get('tool', 'none')}' has no Maestri preset; "
                         f"run it outside the canvas")
    lines.append("Write-Output 'Maestri roles updated.'")
    return "\n".join(lines) + "\n"


def agents_md_block(rules: list[Unit], workflows: list[Unit], skills: list[Unit], personas: list[Unit],
                    profile: Profile, root) -> str:
    parts = [AGENTS_BEGIN, "", f"## Engineering harness (profile {profile.name})", "",
             "These rules were composed by engineering-harness. The full trace (what was loaded, why, from where, "
             "overrides and conflicts) is in `.harness/resolution.md`.", ""]
    if personas:
        parts += ["### Personas", ""]
        parts += [f"- **{u.name}**: {u.description}" for u in personas]
        parts += [""]
    if skills or workflows:
        parts += ["### Skills and workflows available on demand", ""]
        parts += [f"- `{u.name}`: {u.description}" for u in workflows + skills]
        parts += [""]
    parts += ["### Rules in force", ""]
    for rule in rules:
        rel = rule.path.relative_to(root).as_posix()
        body = rule.body.strip()
        # Demote headings so the rule nests under this section.
        body = "\n".join("##" + line if line.startswith("#") else line for line in body.splitlines())
        parts += [f"<!-- source: {rel} ({rule.id} v{rule.m('version')}) -->", body, ""]
    parts.append(AGENTS_END)
    return "\n".join(parts) + "\n"
